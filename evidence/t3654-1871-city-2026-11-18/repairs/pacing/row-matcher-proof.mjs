import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
const path = '/workspace/chicago/chicago/4d/tools/qa_pacing_read_t2732.mjs';
const source = fs.readFileSync(path, 'utf8');
const match = source.match(/function readingRowsHaveRatios\(text\) \{[\s\S]*?\n\}/);
assert.ok(match, 'extract the exact current verifier helper');
const valid = vm.runInNewContext(`(${match[0]})`);
const report = JSON.parse(fs.readFileSync('/tmp/t3654-pacing-1871-attempt1/t3654-pacing-1871-browser-report.json', 'utf8'));
const text = report.viaButton.text;
const first = text.split('\n').find(line => /^walk\s+fixed/.test(line));
const tokens = first.split(',')[0].trim().split(/\s+/);
const withTokens = (values) => text.replace(first, values.join(' ') + ', driver draws 95 (max 95)');
const checks = [];
function check(name, candidate, expected) { assert.equal(valid(candidate), expected, name); checks.push({name, expected, pass:true}); }
check('Actual captured rows with driver-draw annotations', text, true);
check('Bare ratio rows without optional annotations', text.replace(/, driver draws \d+ \(max \d+\)/g, ''), true);
check('Known switch, paced-share and driver suffixes in formatter order', text.replace(', driver draws 95 (max 95)', ', 1 switch (1 of the >50 on one), paced 25 %, driver draws 95 (max 95)'), true);
check('Known plural switch suffix', text.replace(', driver draws 95 (max 95)', ', 2 switches (3 of the >50 on one), driver draws 95 (max 95)'), true);
check('Missing ratio rejected despite driver count at end', withTokens(tokens.slice(0, -1)), false);
const malformed = [...tokens]; malformed[4] = 'NaN';
check('Malformed numeric measurement rejected', withTokens(malformed), false);
const noninteger = [...tokens]; noninteger[2] = '4.5';
check('Fractional draw count rejected', withTokens(noninteger), false);
const reversed = [...tokens]; reversed[10] = '1.5-1';
check('Reversed ratio range rejected', withTokens(reversed), false);
check('Malformed suffix numeric count rejected', text.replace('driver draws 95 (max 95)', 'driver draws many (max 95)'), false);
check('Malformed suffix punctuation rejected', text.replace('driver draws 95 (max 95)', 'driver draws 95 (max 95'), false);
check('Unknown trailing suffix rejected', text.replace('driver draws 95 (max 95)', 'unrecognized trailing text'), false);
check('Repeated suffix rejected', text.replace(', driver draws 95 (max 95)', ', driver draws 95 (max 95), driver draws 95 (max 95)'), false);
check('Out-of-order suffix rejected', text.replace(', driver draws 95 (max 95)', ', driver draws 95 (max 95), paced 25 %'), false);
check('Missing mode row rejected', text.replace(first + '\n', ''), false);
check('Duplicate move/mode pair rejected', text.replace(first, first.replace('fixed', 'adaptive')), false);
fs.writeFileSync('/tmp/t3654-pacing-row-matcher-proof.json', JSON.stringify({recorded_utc:new Date().toISOString(), source:path, source_sha256:crypto.createHash('sha256').update(source).digest('hex'), actual_row:first, old_matcher:'Requires the row to end in the ratio; rejects the existing driver-draw suffix.', new_matcher:'Exactly six distinct move/mode pairs; all eight numeric metrics and positive ratio/range; only known optional switch, paced-share and driver-draw suffixes in formatter order.', checks},null,2)+'\n');
console.log(`PASS: ${checks.length} exact-verifier cases, including actual captured rows and malformed/missing-ratio negatives.`);
